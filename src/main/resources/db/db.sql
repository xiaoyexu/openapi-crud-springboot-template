  AUDIT_ID                BIGINT AUTO_INCREMENT,
  CONSTRAINT PK_STUDENTS_AUDIT PRIMARY KEY (AUDIT_ID),
  ACTION                  VARCHAR(1) NOT NULL,
  ID                      VARCHAR(50) NOT NULL,
  NAME                    VARCHAR(200) NOT NULL,
